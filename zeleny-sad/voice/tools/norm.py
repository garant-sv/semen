# Formulas from the hints, said the way a teacher says them.
PHRASES = {
    'Подсказка: Цена умножить на количество.': 'Подсказка: Цену умножь на количество.',
    'Подсказка: Площадь прямоугольника равно длина умножить на ширина.': 'Подсказка: Площадь прямоугольника равна длине, умноженной на ширину.',
    'Подсказка: Стоимость равно цена умножить на количество.': 'Подсказка: Стоимость равна цене, умноженной на количество.',
    'Подсказка: Расстояние равно скорость умножить на время.': 'Подсказка: Расстояние равно скорости, умноженной на время.',
    'равно (длина + ширина)': 'равен сумме длины и ширины,',
    'умножить на 2.': 'умноженной на два.',
}
UNITS_DAT = {'м²': ('квадратному метру', 'квадратным метрам'), 'м': ('метру', 'метрам'), 'мин': ('минуте', 'минутам')}


def spell(text: str) -> str:
    t = PHRASES.get(text, text)
    # «равно 16 м» → «равно шестнадцати метрам».
    t = re.sub(r'равно (\d+) (м²|мин|м)(?![а-яё])', lambda m: f'равно {num(int(m[1]), "dat", "f" if m[2] == "мин" else "m")} {UNITS_DAT[m[2]][0 if int(m[1]) % 10 == 1 and int(m[1]) % 100 != 11 else 1]}', t)
    # Fixed phrases first.
    t = re.sub(r'\bВ 1 часе 60 минут\b', 'В одном часе шестьдесят минут', t)
    t = re.sub(r'\b1-е склонение', 'первое склонение', t)
    t = re.sub(r'\b2-е склонение', 'второе склонение', t)
    t = re.sub(r'\b3-е склонение', 'третье склонение', t)
    t = re.sub(r'\bII спряжение', 'второе спряжение', t)
    t = re.sub(r'\bI спряжение', 'первое спряжение', t)
    # Letters said by name, as at school.
    t = re.sub(r'\bбуква ь\b', 'мягкий знак', t)
    t = re.sub(r'\bбуква ъ\b', 'твёрдый знак', t)
    t = re.sub(r'\bбуква ([бвгджзклмнпрстфхцчшщ])\b', lambda m: 'буква ' + LETTER[m[1]], t)
    t = re.sub(r'\bразделительный Ь', 'разделительный мягкий знак', t)
    t = t.replace('Ь', 'мягкий знак').replace('Ъ', 'твёрдый знак')
    t = re.sub(r'\bбез т:', 'без буквы тэ:', t)
    t = re.sub(r'\bтам л слышна', 'там эль слышна', t)
    t = re.sub(r'приставки (об|под|с)- перед (е|я)\b', r'приставки \1, перед буквой \2', t)
    t = re.sub(r'(на|окончание) -(ить|ет|ит)\b', r'\1 \2', t)
    # Stress written in the game's text (во́ды) → the model's mark (в+оды).
    t = re.sub(r'([аеёиоуыэюяАЕЁИОУЫЭЮЯ])\u0301', r'+\1', t)
    t = t.replace(' + ', ' плюс ')
    t = t.replace('твёрдой (лёд, снег) и', 'твёрдой — это лёд и снег, — и')
    t = t.replace('(что делать?):', '— отвечает на вопрос «что делать?», —')
    t = t.replace('в 1519 – 1522 годах', 'с тысяча пятьсот девятнадцатого по тысяча пятьсот двадцать второй год')
    # Quest progress: «Починить мостик (5/15 лепестков).»
    t = re.sub(r' \((\d+)/(\d+) лепестков\)', lambda m: f': {num(int(m[1]))} {plural(int(m[1]), ("лепесток", "лепестка", "лепестков"))} из {num(int(m[2]), "gen")}', t)
    t = re.sub(r'\bиз (\d+) лепестков', lambda m: f'из {num(int(m[1]), "gen")} лепестков', t)
    # «3 из 18» → «три из восемнадцати»
    t = re.sub(r'(\d+) из (\d+)', lambda m: f'{num(int(m[1]))} из {num(int(m[2]), "gen")}', t)
    # «нас 4 —» → «нас четверо —»
    t = re.sub(r'\bнас (\d+)', lambda m: f'нас {COLLECTIVE.get(int(m[1]), num(int(m[1])))}', t)
    # «На 1 м²» → «На один квадратный метр»; numbers with units.
    def unit_rep(m):
        n, u = int(m[1]), m[2]
        case = 'nom'
        return f'{num(n, case, UNIT_GENDER[u])} {plural(n, UNITS[u])}'
    t = re.sub(r'(\d+) (м²|мин|шт|ч|м)(?![а-яё])\.?(?=\s|$|[.,;:!?)—])', lambda m: unit_rep(m) + ('.' if m[0].endswith('.') else ''), t)
    # Results: «равно 18» → «равно восемнадцати» (dative, as at school).
    t = re.sub(r'равно (\d+)', lambda m: f'равно {num(int(m[1]), "dat")}', t)
    # «по 21 лепестку» (dative), «по 3 лепестка».
    t = re.sub(r'\bпо (\d+) (лепестку)', lambda m: f'по {(num(int(m[1]) - 1) + " ") if int(m[1]) > 1 else ""}одному {m[2]}', t)
    # Number before a noun: gender from the noun, accusative = nominative except «одну».
    t = re.sub(r'(\d+) ([А-Яа-яЁё]+)', lambda m: f'{num(int(m[1]), "acc", gender_of(m[2]))} {m[2]}', t)
    # Remaining bare numbers (in sums): nominative.
    t = re.sub(r'\d+', lambda m: num(int(m[0])), t)
    # Signs that may be left.
    t = t.replace('(', '').replace(')', '').replace('–', '—')
    t = re.sub(r'\.\.$', '.', t)
    t = re.sub(r'\s+', ' ', t).strip()
    return t


def ord_years(y: int) -> str:
    # 1519 – 1522 годах: «тысяча пятьсот девятнадцатом – тысяча пятьсот двадцать втором».
    ORD_P = {9: 'девятнадцатом', 2: 'двадцать втором', 1: 'двадцать первом', 0: 'двадцатом'}
    h, r = divmod(y, 100)
    head = 'тысяча ' + HUND[h - 10] if h >= 10 else ''
    words = {19: 'девятнадцатом', 20: 'двадцатом', 21: 'двадцать первом', 22: 'двадцать втором'}
    return f'{head} {words.get(r, num(r))}'.strip()


