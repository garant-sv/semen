TEENS_OBL = [t[:-1] + 'и' for t in TEENS]
TENS_G = ['', '', 'двадцати', 'тридцати', 'сорока', 'пятидесяти', 'шестидесяти', 'семидесяти', 'восьмидесяти', 'девяноста']
HUND_G = ['', 'ста', 'двухсот', 'трёхсот', 'четырёхсот', 'пятисот', 'шестисот', 'семисот', 'восьмисот', 'девятисот']
HUND_D = ['', 'ста', 'двумстам', 'трёмстам', 'четырёмстам', 'пятистам', 'шестистам', 'семистам', 'восьмистам', 'девятистам']
HUND_P = ['', 'ста', 'двухстах', 'трёхстах', 'четырёхстах', 'пятистах', 'шестистах', 'семистах', 'восьмистах', 'девятистах']


def num(n: int, case='nom', gender='m') -> str:
    """case: nom, acc, gen, dat, prep. gender: m, f, n."""
    if n >= 1000:
        th, rest = divmod(n, 1000)
        if case in ('nom', 'acc'):
            w = num(th, 'nom', 'f')
            m10, m100 = th % 10, th % 100
            t = 'тысяча' if m10 == 1 and m100 != 11 else 'тысячи' if 2 <= m10 <= 4 and not 12 <= m100 <= 14 else 'тысяч'
            if case == 'acc' and t == 'тысяча':
                t = 'тысячу'
                w = w.replace('одна', 'одну')
            head = f'{w} {t}'
        else:
            head = f'{num(th, case, "f")} тысяч'  # enough for this game (never used)
        return head if rest == 0 else f'{head} {num(rest, case, gender)}'
    if n == 0:
        return {'nom': 'ноль', 'acc': 'ноль', 'gen': 'ноля', 'dat': 'нолю', 'prep': 'ноле'}[case]
    h, r = divmod(n, 100)
    t, o = divmod(r, 10)
    words = []
    obl = case in ('gen', 'dat', 'prep')
    if h:
        words.append({'gen': HUND_G, 'dat': HUND_D, 'prep': HUND_P}.get(case, HUND)[h])
    if t == 1:
        words.append(TEENS_OBL[o] if obl else TEENS[o])
    else:
        if t:
            words.append(TENS_G[t] if obl else TENS[t])
        if o:
            if case == 'gen':
                words.append((ONES_G_F if gender == 'f' else ONES_G)[o])
            elif case == 'dat':
                words.append('одной' if (o == 1 and gender == 'f') else ONES_D[o])
            elif case == 'prep':
                words.append('одной' if (o == 1 and gender == 'f') else ONES_P[o])
            else:
                if gender == 'f':
                    w = ONES_F[o]
                    if case == 'acc' and o == 1:
                        w = 'одну'
                elif gender == 'n' and o == 1:
                    w = 'одно'
                else:
                    w = ONES_M[o]
                words.append(w)
    return ' '.join(words)


def plural(n, forms):
    m10, m100 = n % 10, n % 100
    if m10 == 1 and m100 != 11:
        return forms[0]
    if 2 <= m10 <= 4 and not 12 <= m100 <= 14:
        return forms[1]
    return forms[2]


# Gender of the noun that follows a number (by the start of the word).
FEM = ('морковк', 'морковок', 'тыкв', 'корзин', 'секунд', 'минут', 'штук')
MASC = ('лепест', 'букет', 'тюльпан', 'пуч', 'подсолнух', 'куст', 'цвет', 'метр', 'час', 'год')


def gender_of(word: str) -> str:
    w = word.lower()
    if w.startswith(FEM):
        return 'f'
    return 'm'


