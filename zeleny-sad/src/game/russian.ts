export interface WordView {
  /** The word with the gap shown as «_». */
  masked: string;
  /** The whole word. */
  full: string;
  /** The correct option. */
  answer: string;
}

/** Split a template into the masked text, the full text and the correct option. */
export function viewWord(w: WordTask): WordView {
  const gaps = [...w.t.matchAll(/\[([^\]]*)\]/g)];
  // The first bracket that is not the last one is part of the word; the last bracket is the gap.
  const last = gaps[gaps.length - 1];
  let masked = '';
  let full = '';
  let i = 0;
  for (const g of gaps) {
    const before = w.t.slice(i, g.index);
    masked += before;
    full += before;
    if (g === last) masked += '_';
    else masked += g[1];
    full += g[1];
    i = (g.index ?? 0) + g[0].length;
  }
  masked += w.t.slice(i);
  full += w.t.slice(i);
  return { masked, full, answer: last[1] === '' ? NO_LETTER : last[1] };
}

